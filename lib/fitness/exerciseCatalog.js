// lib/fitness/exerciseCatalog.js — the canonical Exercise database. This is
// the core of the workout architecture: a workout no longer embeds a bare
// exercise name + hand-picked equipment ids (the old model). Instead, a
// WorkoutExercise just references one of these by `exerciseId`, and
// everything else -- target muscles, movement pattern, required equipment,
// a demo GIF, instructions -- comes from here automatically.
//
// Sourced from Anatome's bundled free-exercise-db dataset (MIT/Unlicense,
// see https://github.com/NextSolutionsStudio/anatome and
// https://github.com/yuhonas/free-exercise-db) rather than a live API call:
// that dataset is static and versioned, so treating it as *seed data authored
// once* is both more reliable (works even if api.anatome.dev is down -- see
// gifUrl() below, which is the only live network dependency, and even that
// degrades gracefully) and easier to keep correct than re-deriving it from a
// runtime fetch every time. `apiExerciseId` is the free-exercise-db ext_id,
// kept around so a demo GIF can be constructed from Anatome's hosted,
// license-cleared /exerciseGif endpoint without bundling any media here.
//
// `equipmentSlots` is an array of "slots"; every slot must have at least one
// option present at a gym for the exercise to count as available there. Most
// exercises have exactly one slot with one or more interchangeable options
// (e.g. lat pulldown: one slot, several machine types that all work equally
// well). A compound exercise like barbell bench press genuinely needs two
// *different* things at once (a barbell AND a bench), so it gets two slots.
// This is what keeps "required equipment" and "compatible equipment" from
// collapsing into the same flat, ambiguous list -- see equipmentCatalog.js
// for what each id refers to. The first option in each slot is the
// "canonical" one shown in compact UI; the rest only matter for the
// gym-availability check.
