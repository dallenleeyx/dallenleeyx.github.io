export const MOVEMENT_PATTERNS = ['push', 'pull', 'squat', 'hinge', 'isolation', 'compound', 'core'];

// `gymGifsId` is a "{muscle}/{slug}" id into ExerciseGymGifsDB (see
// exerciseMedia.js) -- a real multi-frame animated demo GIF, unlike
// Anatome's `apiExerciseId` media which (per Anatome's own source) is just
// a 2-frame photo flip. Where both are set, exerciseGifUrl() prefers
// gymGifsId; apiExerciseId still always drives the muscle diagram and
// remains the fallback demo media when an exercise has no gymGifsId match.
function ex({
  id, canonicalName, aliases = [], bodyParts, primaryMuscles, secondaryMuscles = [],
  movementPattern, equipmentSlots, instructions, apiExerciseId, gymGifsId,
}) {
  return {
    id,
    canonicalName,
    aliases,
    bodyParts,
    primaryMuscles,
    secondaryMuscles,
    movementPattern,
    equipmentSlots,
    instructions,
    demoMedia: apiExerciseId ? { source: 'anatome', apiExerciseId } : null,
    apiSource: apiExerciseId ? 'anatome' : 'custom',
    apiExerciseId: apiExerciseId || null,
    gymGifsId: gymGifsId || null,
    custom: false,
  };
}

